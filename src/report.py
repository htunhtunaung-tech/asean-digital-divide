"""Step 5 — Write reports/findings.md from the computed results.

Every number in the findings file is pulled from the CSVs the earlier steps
produced, so re-running the pipeline on newer data rewrites the findings too.
The wording is deliberately cautious: these are associations, not causal effects.

Usage:
    python -m src.report
"""
from __future__ import annotations

import pandas as pd

from . import config


def _fmt(v, nd=1, suffix=""):
    return "n/a" if pd.isna(v) else f"{v:,.{nd}f}{suffix}"


def _year(v):
    return "n/a" if pd.isna(v) else str(int(v))


def main() -> str:
    R = config.REPORTS
    trends = pd.read_csv(R / "trend_summary.csv")
    leader = pd.read_csv(R / "trend_meta.csv", index_col=0).iloc[0, 0]
    reg = pd.read_csv(R / "regression_results.csv")
    clusters = pd.read_csv(R / "clusters.csv")
    scores = pd.read_csv(R / "cluster_selection.csv")

    focus = config.COUNTRIES[config.FOCUS_COUNTRY]
    y0, y1 = _year(trends["latest_year"].min()), _year(trends["latest_year"].max())
    year_span = y0 if y0 == y1 else f"{y0}–{y1}"
    f = trends[trends["iso3"] == config.FOCUS_COUNTRY].iloc[0]
    median_latest = trends["internet_latest"].median()
    fastest = trends.sort_values("avg_gain_pp_per_year_since_2010", ascending=False).iloc[0]
    lowest = trends.sort_values("internet_latest").iloc[0]

    def coef(model_prefix, var):
        r = reg[(reg["model"].str.startswith(model_prefix)) & (reg["variable"] == var)]
        return r.iloc[0] if len(r) else None

    pooled = coef("(1)", "internet_10pp")
    twfe = coef("(3)", "internet_10pp")
    lagged = coef("(4)", "internet_10pp_lag1")

    def describe(r):
        if r is None:
            return "could not be estimated (not enough data)"
        sig = "the 95% interval excludes zero" if (r["ci_low"] > 0 or r["ci_high"] < 0) \
            else "the 95% interval includes zero, so we cannot rule out no association"
        return (f"{r['coef']:+.2f} points of secondary enrollment per 10-point rise in internet use "
                f"(95% CI {r['ci_low']:+.2f} to {r['ci_high']:+.2f}; {int(r['n_obs'])} country-years); {sig}")

    focus_cluster = clusters.loc[clusters["iso3"] == config.FOCUS_COUNTRY, "cluster"]
    focus_cluster = focus_cluster.iloc[0] if len(focus_cluster) else "n/a"
    groups = "\n".join(
        f"- **{name}** ({g['cluster_profile'].iloc[0]} than the ASEAN average): {', '.join(g['country'])}"
        for name, g in clusters.sort_values("cluster_rank").groupby("cluster", sort=False)
    )
    imputed = clusters.dropna(subset=["features_imputed"])
    imputed = imputed[imputed["features_imputed"].astype(str).str.len() > 0]
    imputed_note = ("\n\nNo recent data, so the ASEAN median was used for: " + "; ".join(
        f"{r['country']} ({r['features_imputed']})" for _, r in imputed.iterrows()) + ".") if len(imputed) else ""

    md = f"""# Findings

_Auto-generated by `src/report.py` from the pipeline outputs. Edit the wording in the
README for your portfolio; keep the numbers tied to these files._

## 1. Adoption: everyone rose, but not at the same speed
- Using each country's latest year with data ({year_span}),
  the ASEAN median internet use was **{_fmt(median_latest, 1, '%')}**.
  The leader was **{leader}** and the lowest was **{lowest['country']}** ({_fmt(lowest['internet_latest'], 1, '%')}).
- **{fastest['country']}** grew fastest since 2010, at about **{_fmt(fastest['avg_gain_pp_per_year_since_2010'], 1)} percentage points a year**.
- **{focus}:** {_fmt(f['internet_2010'], 1, '%')} in 2010 → {_fmt(f['internet_latest'], 1, '%')} in {_year(f['latest_year'])}
  (its latest year with data), about {_fmt(f['avg_gain_pp_per_year_since_2010'], 1)} points a year;
  {_fmt(f['gap_to_leader_pp'], 1)} points behind {leader} in that same year.

## 2. Internet use and secondary enrollment
- **Naive cross-country view (pooled OLS):** {describe(pooled)}.
- **Comparing each country with itself, net of region-wide trends (two-way FE):** {describe(twfe)}.
- **Using last year's internet use (lagged):** {describe(lagged)}.
- How to read this: if the association shrinks a lot from the pooled model to the
  fixed-effects model, much of the raw correlation reflects stable differences
  between countries (income, institutions) rather than internet growth itself.

## 3. Country groups
k-means on 7 standardized indicators chose **k = {int(scores.loc[scores['silhouette'].idxmax(), 'k'])}**
(silhouette {scores['silhouette'].max():.2f}; values below 0.5 mean the groups overlap, so read them as
tendencies rather than sharp categories). Groups are numbered by average internet use and described by
the two indicators that most set them apart.

{groups}

{focus} falls in **{focus_cluster}**.{imputed_note}

## Limitations
- 11 countries is a small panel; estimates are imprecise and sensitive to specification.
- Gross enrollment can exceed 100% and does not measure learning quality.
- Associations, not causal effects: richer, more urban countries both connect and enroll faster,
  and fixed effects cannot remove factors that change over time within a country.
- Survey years differ by country; gaps up to {config.MAX_INTERP_GAP} years were interpolated
  (see `reports/cleaning_log.md`), longer gaps were left missing.
"""
    (R / "findings.md").write_text(md, encoding="utf-8")
    print("  wrote reports/findings.md")
    return md


if __name__ == "__main__":
    main()